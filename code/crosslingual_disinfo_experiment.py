from openai import OpenAI
import re

client = OpenAI(
    base_url='https://openrouter.ai/api/v1',
    api_key=OPENROUTER_API_KEY,
)

def call_model(model_id, prompt, temperature=0.0, max_tokens=300):
    try:
        response = client.chat.completions.create(
            model=model_id,
            messages=[{'role': 'user', 'content': prompt}],
            temperature=temperature,
            max_tokens=max_tokens,
            extra_headers={
                'HTTP-Referer': 'https://phd-experiment.local',
                'X-Title': 'Cross-Lingual Disinfo Study',
            }
        )
        return response.choices[0].message.content.strip()
    except Exception as e:
        return f'[API_ERROR: {e}]'

def extract_verdict(text):
    text = text.upper()
    m = re.search(r'VERDICT:\s*(FAKE|REAL|UNCERTAIN)', text)
    if m:
        return m.group(1)
    for label in ['FAKE', 'REAL', 'UNCERTAIN']:
        if re.search(rf'\b{label}\b', text):
            return label
    return 'UNPARSEABLE'

