df_results.head(3)

rows = []
for (cid, model, strategy), g in df_results.groupby(['claim_id', 'model', 'prompt_strategy']):
    v = g.set_index('claim_language')['verdict'].to_dict()
    unique = set(x for x in v.values() if x != 'UNPARSEABLE')
    rows.append({
        'claim_id':         cid,
        'model':            model,
        'prompt_strategy':  strategy,
        'verdict_hindi':    v.get('hindi',    'N/A'),
        'verdict_english':  v.get('english',  'N/A'),
        'verdict_estonian': v.get('estonian', 'N/A'),
        'consistent':       len(unique) == 1,
        'n_unique':         len(unique)
    })
df_consistency = pd.DataFrame(rows)

print('=== CONSISTENCY RATE BY MODEL ===')
print(df_consistency.groupby('model')['consistent'].mean().round(3).sort_values(ascending=False))

print('\n=== CONSISTENCY RATE BY PROMPT STRATEGY ===')
print(df_consistency.groupby('prompt_strategy')['consistent'].mean().round(3))

print('\n=== LANGUAGE-PAIR FLIP RATES ===')
pairs = [('hindi','english'), ('hindi','estonian'), ('english','estonian')]
for l1, l2 in pairs:
    flips = total = 0
    for _, g in df_results.groupby(['claim_id','model','prompt_strategy']):
        v = g.set_index('claim_language')['verdict'].to_dict()
        if l1 in v and l2 in v and 'UNPARSEABLE' not in (v[l1], v[l2]):
            total += 1
            if v[l1] != v[l2]:
                flips += 1
    rate = f'{flips/total:.1%}' if total else 'no data'
    print(f'  {l1} -> {l2}: {flips}/{total} flips = {rate}')

print('=== FAKE VERDICT RATE BY LANGUAGE ===')
print(df_results.groupby('claim_language').apply(
    lambda x: (x['verdict'] == 'FAKE').sum() / len(x)
).round(3))

