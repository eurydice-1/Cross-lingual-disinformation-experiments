CONFIDENCE_PROMPT = (
    "You are a fact-checking assistant. Assess the following claim.\n\n"
    "Claim: {claim}\n\n"
    "Respond on exactly two lines and nothing else:\n"
    "Line 1: Your verdict — one of: FAKE / REAL / UNCERTAIN\n"
    "Line 2: Your confidence in that verdict as a number from 1 (very unsure) to 10 (very sure)\n\n"
    "Example output:\n"
    "FAKE\n"
    "7"
)

def extract_verdict_and_confidence(text):
    lines = [l.strip() for l in text.strip().split("\n") if l.strip()]
    verdict = "UNPARSEABLE"
    confidence = None

    # Extract verdict from any line
    for line in lines:
        v = extract_verdict(line)
        if v != "UNPARSEABLE":
            verdict = v
            break

    # Extract confidence — look for a standalone number 1-10
    for line in lines:
        try:
            val = int(line.strip())
            if 1 <= val <= 10:
                confidence = val
                break
        except ValueError:
            import re
            m = re.search(r'\b([1-9]|10)\b', line)
            if m:
                confidence = int(m.group(1))
                break

    return verdict, confidence

