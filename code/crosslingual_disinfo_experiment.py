    for _, row in df_experiment.iterrows():
        for model in MODELS:
            for strategy, template in PROMPT_TEMPLATES.items():
                pbar.update(1)
                key = (str(row['id']), row['claim_language'], model, strategy)
                if key in completed:
                    continue
                prompt  = template.format(claim=row['claim_text'])
                raw     = call_model(model, prompt, temperature=TEMPERATURE)
                verdict = extract_verdict(raw)
                writer.writerow({
                    'claim_id':        row['id'],
                    'claim_language':  row['claim_language'],
                    'gold_label':      row['gold_label'],
                    'source':          row['source'],
                    'claim_text':      str(row['claim_text'])[:200],
                    'model':           model,
                    'prompt_strategy': strategy,
                    'raw_response':    raw[:500],
                    'verdict':         verdict
                })
                f.flush()
                time.sleep(0.2)

    pbar.close()

